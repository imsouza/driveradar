  function resolveLang(pref, systemLocale = 'pt-BR') {
    if (SUPPORTED.includes(pref)) return pref;
    const raw = String(systemLocale || 'pt-BR').toLowerCase();
    if (raw.startsWith('en')) return 'en';
    if (raw.startsWith('es')) return 'es';
    if (raw.startsWith('fr')) return 'fr';
    return 'pt-BR';
  }

  function localeFor(lang) {
    return LOCALES[lang] || 'pt-BR';
  }

  function t(lang, key, vars = null) {
    const resolved = SUPPORTED.includes(lang) ? lang : 'pt-BR';
    const table = DICT[resolved] || DICT['pt-BR'];
    let text = table[key] !== undefined ? table[key] : (DICT['pt-BR'][key] !== undefined ? DICT['pt-BR'][key] : key);
    if (vars) {
      Object.entries(vars).forEach(([k, v]) => {
        text = text.replaceAll(`{${k}}`, String(v));
      });
    }
    return text;
  }

