  function detectLang() {
    try {
      const saved = localStorage.getItem(LANG_KEY);
      if (SUPPORTED.includes(saved)) return saved;
    } catch (_) {}
    const nav = String(navigator.language || 'pt-BR').toLowerCase();
    if (nav.startsWith('en')) return 'en';
    if (nav.startsWith('es')) return 'es';
    if (nav.startsWith('fr')) return 'fr';
    return 'pt-BR';
  }

  let current = detectLang();

  function getLang() {
    return current;
  }

  function setLang(lang) {
    current = SUPPORTED.includes(lang) ? lang : 'pt-BR';
    try { localStorage.setItem(LANG_KEY, current); } catch (_) {}
    document.documentElement.lang = current;
    return current;
  }

  function locale() {
    return LOCALES[current] || 'pt-BR';
  }

  function t(key, vars = null, fallback = '') {
    const table = DICT[current] || DICT['pt-BR'];
    let text = table[key] !== undefined ? table[key] : (DICT['pt-BR'][key] !== undefined ? DICT['pt-BR'][key] : fallback || key);
    if (vars) {
      Object.entries(vars).forEach(([k, v]) => {
        text = text.replaceAll(`{${k}}`, String(v));
      });
    }
    return text;
  }

  function applyStatic() {
    document.documentElement.lang = current;
    document.title = t('page.title');
    document.querySelectorAll('[data-i18n]').forEach((el) => {
      el.textContent = t(el.dataset.i18n, null, el.textContent);
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
      el.placeholder = t(el.dataset.i18nPlaceholder, null, el.placeholder);
    });
    document.querySelectorAll('[data-i18n-title]').forEach((el) => {
      el.title = t(el.dataset.i18nTitle, null, el.title);
    });
  }

  window.DriveRadarI18n = { SUPPORTED, getLang, setLang, locale, t, applyStatic };
